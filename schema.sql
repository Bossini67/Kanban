create table if not exists public.cards (
    id bigint generated by default as identity primary key,
    title text not null,
    status text not null default 'todo'
        check (status in ('todo', 'doing', 'done')),
    created_at timestamptz not null default now()
);

alter table public.cards enable row level security;

grant select, insert, update, delete on public.cards to anon;
grant usage, select on sequence public.cards_id_seq to anon;

drop policy if exists cards_public_select on public.cards;
create policy cards_public_select
    on public.cards for select to anon
    using (true);

drop policy if exists cards_public_insert on public.cards;
create policy cards_public_insert
    on public.cards for insert to anon
    with check (true);

drop policy if exists cards_public_update on public.cards;
create policy cards_public_update
    on public.cards for update to anon
    using (true)
    with check (true);

drop policy if exists cards_public_delete on public.cards;
create policy cards_public_delete
    on public.cards for delete to anon
    using (true);
